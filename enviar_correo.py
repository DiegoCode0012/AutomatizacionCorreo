import os
import smtplib
from email.message import EmailMessage

# Configuración del remitente y destinatario
REMITENTE = "diegoburneo@gmail.com"
DESTINATARIO = "diegoburneoh@gmail.com"

# Lee la contraseña de aplicación de forma segura desde los secretos de GitHub
PASSWORD_APP = os.environ.get("MAIL_PASS")

# Creación del mensaje
mensaje = EmailMessage()
mensaje["From"] = REMITENTE
mensaje["To"] = DESTINATARIO
mensaje["Subject"] = "Correo automatizado desde GitHub Actions"
mensaje.set_content("¡Hola! Este correo se envió automáticamente desde la nube de GitHub sin necesidad de tener tu PC encendida.")

# Envío del correo usando SSL (Puerto 465)
try:
    print("Conectando con el servidor de Gmail...")
    with smtplib.SMTP_SSL("smtp.gmail.com", 465) as servidor:
        servidor.login(REMITENTE, PASSWORD_APP)
        servidor.send_message(mensaje)

    print("¡Correo enviado con éxito!")

except Exception as e:
    print(f"Error al enviar el correo: {e}")